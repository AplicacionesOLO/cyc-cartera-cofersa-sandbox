/**
 * Arma el texto de domicilio para el pagaré a partir de la dirección
 * estructurada, en el orden que usan los documentos legales en Costa Rica
 * (señas primero, de lo más específico a lo más general: señas, distrito,
 * cantón, provincia). Se manda tal cual a las columnas *_domicilio existentes
 * (deudor_domicilio, representante_domicilio, fiador_domicilio) -- no hay
 * columnas nuevas, esto es sólo cómo se arma el texto en el formulario.
 */
export function formatearDireccion(p: {
  provincia: string;
  canton: string;
  distrito: string;
  senas: string;
}): string {
  const partes = [p.senas.trim(), p.distrito.trim(), p.canton.trim(), p.provincia.trim()].filter(
    Boolean,
  );
  return partes.join(', ');
}
